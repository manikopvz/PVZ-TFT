void GridItem::GridItemDie()
{
    if (mDead) return;
    if (mGridItemType == GridItemType::GRIDITEM_GRAVESTONE && mBoard &&
        (mBoard->HasAugment(RollAugment::AUGMENT_GRAVE_HARVEST) || mBoard->HasAugment(RollAugment::AUGMENT_GRAVE_HARVEST_II)))
        mBoard->DropRegularSun(2, mBoard->GridToPixelX(mGridX,mGridY) + 40,
                                mBoard->GridToPixelY(mGridX,mGridY) + 40);
    mDead = true;
    
    Reanimation* aGridItemReanim = mApp->ReanimationTryToGet(mGridItemReanimID);
    if (aGridItemReanim)
    {
        aGridItemReanim->ReanimationDie();
        mGridItemReanimID = ReanimationID::REANIMATIONID_NULL;
    }

    TodParticleSystem* aGridItemParticle = mApp->ParticleTryToGet(mGridItemParticleID);
    if (aGridItemParticle)
    {
        aGridItemParticle->ParticleSystemDie();
    }
}

Sexy::Rect GridItem::GetGraveStoneRect()
{
    if (mDead || mGridItemType != GridItemType::GRIDITEM_GRAVESTONE || mGridItemCounter < 100 || !mBoard)
        return Sexy::Rect(0, 0, 0, 0);

    int aCelHeight = IMAGE_TOMBSTONES->GetCelHeight();
    int aGraveCol = 0;
    int aGraveRow = 0;
    GetGraveStoneSpriteCell(this, aGraveCol, aGraveRow);

    int aMinX = sGraveStoneMaskBounds[aGraveRow][aGraveCol][0];
    int aMinY = sGraveStoneMaskBounds[aGraveRow][aGraveCol][1];
    int aMaxX = sGraveStoneMaskBounds[aGraveRow][aGraveCol][2];
    int aMaxY = sGraveStoneMaskBounds[aGraveRow][aGraveCol][3];
    int aOffsetX = mBoard->mGridCelOffset[mGridX][mGridY][0];
    int aOffsetY = mBoard->mGridCelOffset[mGridX][mGridY][1];
    int aSpriteX = mBoard->GridToPixelX(mGridX, mGridY) + aOffsetX - 4;
    int aSpriteTopY = mBoard->GridToPixelY(mGridX, mGridY) + aCelHeight + aOffsetY - 9 - aCelHeight;
    return Sexy::Rect(aSpriteX + aMinX, aSpriteTopY + aMinY, aMaxX - aMinX + 1, aMaxY - aMinY + 1);
}

bool GridItem::GraveStoneIntersectsRect(const Sexy::Rect& theRect)
{
    if (theRect.mWidth <= 0 || theRect.mHeight <= 0)
        return false;

    Sexy::Rect aBounds = GetGraveStoneRect();
    if (!GraveStoneRectsOverlap2D(aBounds, theRect))
        return false;

    int aCelHeight = IMAGE_TOMBSTONES->GetCelHeight();
    int aGraveCol = 0;
    int aGraveRow = 0;
    GetGraveStoneSpriteCell(this, aGraveCol, aGraveRow);

    int aOffsetX = mBoard->mGridCelOffset[mGridX][mGridY][0];
    int aOffsetY = mBoard->mGridCelOffset[mGridX][mGridY][1];
    int aSpriteX = mBoard->GridToPixelX(mGridX, mGridY) + aOffsetX - 4;
    int aSpriteTopY = mBoard->GridToPixelY(mGridX, mGridY) + aCelHeight + aOffsetY - 9 - aCelHeight;
    int aRectRight = theRect.mX + theRect.mWidth;
    int aRectBottom = theRect.mY + theRect.mHeight;

    for (int y = 0; y < 91; ++y)
    {
        int aScreenY = aSpriteTopY + y;
        if (aScreenY < theRect.mY || aScreenY >= aRectBottom)
            continue;

        for (int aRun = 0; aRun < 8; aRun += 2)
        {
            int aLeft = sGraveStoneMaskRuns[aGraveRow][aGraveCol][y][aRun];
            if (aLeft == 255)
                break;
            int aRight = sGraveStoneMaskRuns[aGraveRow][aGraveCol][y][aRun + 1];
            int aSpanLeft = aSpriteX + aLeft;
            int aSpanRight = aSpriteX + aRight + 1;
            if (theRect.mX < aSpanRight && aRectRight > aSpanLeft)
                return true;
        }
    }

    return false;
}

void GridItem::TakeDamage(int theDamage, bool theInstantKill)
{
    // Tombstones are durable blockers, not ordinary destructible grid items.
    // Instant-kill effects (including Cob Cannon's kill-all blast) must not affect them.
    if (mDead || mGridItemType != GridItemType::GRIDITEM_GRAVESTONE || theDamage <= 0 || theInstantKill)
        return;

    // Keep the grave robust if a future creation path forgets to initialize HP.
    if (mGridItemHealth <= 0)
        mGridItemHealth = 1800;

    int aPreviousHealth = mGridItemHealth;
    mGridItemHealth = max(0, mGridItemHealth - theDamage);
    if (mGridItemHealth < aPreviousHealth)
        mGraveHitCounter = 25;
    if (mGridItemHealth <= 0)
        GridItemDie();
}

