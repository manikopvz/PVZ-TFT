static void GetGraveStoneSpriteCell(const GridItem* theGraveStone, int& theCol, int& theRow)
{
    int aGridCelLook = theGraveStone->mBoard->mGridCelLook[theGraveStone->mGridX][theGraveStone->mGridY];
    theCol = aGridCelLook % 5;
    if (theGraveStone->mGridY == 0)
    {
        theRow = 1;
    }
    else if (theGraveStone->mGridItemState == GridItemState::GRIDITEM_STATE_GRAVESTONE_SPECIAL)
    {
        theRow = 0;
    }
    else
    {
        theRow = 2 + aGridCelLook % 2;
    }
}

static bool GraveStoneRectsOverlap2D(const Rect& theFirst, const Rect& theSecond)
{
    return theFirst.mX < theSecond.mX + theSecond.mWidth &&
        theFirst.mX + theFirst.mWidth > theSecond.mX &&
        theFirst.mY < theSecond.mY + theSecond.mHeight &&
        theFirst.mY + theFirst.mHeight > theSecond.mY;
}

